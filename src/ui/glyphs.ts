export const glyphPaths = Object.fromEntries(
  Object.entries(glyphs).map(([id, rows]) => {
    const path = (ink: string) =>
      rows
        .flatMap((row, y) =>
          [...row.matchAll(new RegExp(ink + '+', 'g'))].map(
            (match) => `M${match.index} ${y}h${match[0].length}v1h-${match[0].length}z`,
          ),
        )
        .join('');
    return [id, { shape: path('1'), light: path('2') }];
  }),
) as Record<UpgradeId, { shape: string; light: string }>;
